"""Trade-execution database models — Order + Position + TradeFill.

Three tables that together form the audit trail for every trade:

  1. **Order** — every order INTENT the user has acknowledged. Created
     BEFORE the order hits the broker; populated with broker's order_id
     after placement; updated as the order moves through the lifecycle.

  2. **Position** — currently-open positions. Computed from filled orders
     plus broker reconciliation. One OPEN row per (user, symbol, product).

  3. **TradeFill** — every individual fill. Multiple fills can roll up
     to one Order (partial fills). Source of truth for realized P&L.

Why we don't trust the broker alone:
  • Network can drop after the order is placed but before we record the ack
  • Our own audit trail is needed for tax reporting + regulatory queries
  • If broker session expires, our DB still has the user's open positions
  • Reconciliation logic compares our view vs broker's daily

These tables are NEW — they coexist with the legacy `trades` table (kept
for the simpler signal-recommendation flow). New trading code uses these.
"""
from datetime import datetime
from sqlalchemy import (
    Column, String, Float, DateTime, Integer, Boolean, ForeignKey, Index, JSON
)
from sqlalchemy.sql import func

from app.database import Base


# Status state machine. Documented here so callers can reference constants
# instead of bare strings.
ORDER_STATUS_PENDING_RISK   = "PENDING_RISK_CHECK"
ORDER_STATUS_PENDING_BROKER = "PENDING_BROKER"
ORDER_STATUS_OPEN           = "OPEN"
ORDER_STATUS_PARTIAL        = "PARTIAL"
ORDER_STATUS_FILLED         = "FILLED"
ORDER_STATUS_CANCELLED      = "CANCELLED"
ORDER_STATUS_REJECTED       = "REJECTED"
ORDER_STATUS_FAILED         = "FAILED"

# Terminal statuses — no further updates allowed
TERMINAL_ORDER_STATUSES = {
    ORDER_STATUS_FILLED, ORDER_STATUS_CANCELLED,
    ORDER_STATUS_REJECTED, ORDER_STATUS_FAILED,
}


class Order(Base):
    """One row per order intent.

    Lifecycle:
      PENDING_RISK_CHECK
        → PENDING_BROKER     (risk guard passed)
        → OPEN               (broker acked)
        → PARTIAL            (fills coming in)
        → FILLED             (terminal)
        → CANCELLED          (terminal)
        → REJECTED           (terminal — broker refused)
        → FAILED             (terminal — our pre-check refused, or network error)

    Idempotency: `client_order_id` is a UUID generated by the executor
    BEFORE calling the broker. If the same user attempts the same trade
    twice within a short window, the duplicate is rejected at the executor
    level — protects against double-click + network retry race conditions.
    """
    __tablename__ = "exec_orders"

    id              = Column(Integer, primary_key=True, autoincrement=True)
    user_id         = Column(Integer, ForeignKey("users.id"), index=True, nullable=False)

    # Source of this trade — for analytics: which signals get acted on?
    source_signal_id = Column(Integer, index=True, nullable=True)
    source_type     = Column(String(16), default="MANUAL", index=True)

    # Idempotency
    client_order_id = Column(String(64), unique=True, index=True, nullable=False)

    # Trade parameters as USER acknowledged (NOT what came back from broker)
    symbol          = Column(String(32), index=True, nullable=False)
    exchange        = Column(String(8),  default="NSE")
    direction       = Column(String(8),  nullable=False)        # BUY / SELL
    quantity        = Column(Integer,    nullable=False)
    product_type    = Column(String(16), default="DELIVERY")    # DELIVERY/INTRADAY/MARGIN
    order_type      = Column(String(16), default="MARKET")      # MARKET/LIMIT/SL/SL-M
    price           = Column(Float, nullable=True)              # LIMIT price
    trigger_price   = Column(Float, nullable=True)              # for SL / SL-M

    # Companion stop-loss + targets — stored even if broker doesn't support
    # bracket orders, so we can simulate them locally and audit them later.
    stoploss        = Column(Float, nullable=True)
    target_1        = Column(Float, nullable=True)
    target_2        = Column(Float, nullable=True)
    target_3        = Column(Float, nullable=True)

    # Lifecycle
    status          = Column(String(24), default=ORDER_STATUS_PENDING_RISK, index=True)
    placed_at       = Column(DateTime, server_default=func.now(), index=True)
    updated_at      = Column(DateTime, server_default=func.now(), onupdate=func.now())
    filled_at       = Column(DateTime, nullable=True)
    cancelled_at    = Column(DateTime, nullable=True)

    # Broker-side identifiers (filled after placement)
    broker_order_id = Column(String(64), index=True, nullable=True)
    broker_response = Column(JSON, nullable=True)
    broker_status   = Column(String(32), nullable=True)

    # Execution result (rolled up from TradeFills)
    filled_quantity = Column(Integer, default=0)
    avg_fill_price  = Column(Float, nullable=True)
    realized_pnl    = Column(Float, default=0.0)

    # Risk-guard snapshot at order placement — for post-hoc audit
    risk_guard_snapshot = Column(JSON, nullable=True)

    # Paper vs live mode — separate from the broker's own paper concept
    is_paper        = Column(Boolean, default=True, index=True)

    notes           = Column(String(512), nullable=True)

    # ---- Multi-leg grouping (option spreads, condors, straddles) ----
    # When a single user intent creates N legs (e.g. BULL_CALL_SPREAD = BUY ATM CE
    # + SELL OTM CE), all N rows share the same `multi_leg_group_id` UUID and
    # have `leg_index` 0..N-1. NULL on both for plain single-leg orders.
    #
    # The executor uses these to: (a) roll back already-placed legs when a later
    # leg fails, (b) report group-level status, (c) let the UI render the basket
    # as a single trade card. Indexed so leg lookups stay O(log n).
    multi_leg_group_id = Column(String(64), index=True, nullable=True)
    leg_index          = Column(Integer, nullable=True)

    __table_args__ = (
        Index("ix_exec_orders_user_status", "user_id", "status"),
        Index("ix_exec_orders_user_placed", "user_id", "placed_at"),
        Index("ix_exec_orders_user_symbol", "user_id", "symbol"),
        Index("ix_exec_orders_multi_leg",   "multi_leg_group_id"),
    )


class Position(Base):
    """One row per (user, symbol, product_type, status='OPEN'). When net
    quantity hits zero, status becomes CLOSED and the row stays for history.
    """
    __tablename__ = "exec_positions"

    id              = Column(Integer, primary_key=True, autoincrement=True)
    user_id         = Column(Integer, ForeignKey("users.id"), index=True, nullable=False)
    symbol          = Column(String(32), index=True, nullable=False)
    exchange        = Column(String(8),  default="NSE")
    product_type    = Column(String(16), default="DELIVERY")

    # Net position. Positive = long, negative = short.
    net_quantity    = Column(Integer, default=0)
    avg_entry_price = Column(Float, default=0.0)        # weighted across fills

    # Companion levels — copied from the most recent order that set them
    current_sl      = Column(Float, nullable=True)
    current_t1      = Column(Float, nullable=True)
    current_t2      = Column(Float, nullable=True)
    current_t3      = Column(Float, nullable=True)

    # Lifecycle
    opened_at       = Column(DateTime, server_default=func.now())
    closed_at       = Column(DateTime, nullable=True)
    status          = Column(String(16), default="OPEN", index=True)

    # P&L — realized is locked-in, unrealized is computed at read time
    realized_pnl    = Column(Float, default=0.0)

    is_paper        = Column(Boolean, default=True, index=True)

    __table_args__ = (
        Index("ix_exec_positions_user_status", "user_id", "status"),
        Index("ix_exec_positions_user_sym_prod", "user_id", "symbol", "product_type"),
    )


class TradeFill(Base):
    """Atomic fill — one row per partial fill. Source of truth for P&L."""
    __tablename__ = "exec_trade_fills"

    id              = Column(Integer, primary_key=True, autoincrement=True)
    order_id        = Column(Integer, ForeignKey("exec_orders.id"), index=True, nullable=False)
    user_id         = Column(Integer, ForeignKey("users.id"), index=True, nullable=False)

    symbol          = Column(String(32), index=True, nullable=False)
    direction       = Column(String(8),  nullable=False)
    quantity        = Column(Integer, nullable=False)
    price           = Column(Float, nullable=False)

    filled_at       = Column(DateTime, server_default=func.now(), index=True)

    broker_trade_id = Column(String(64), nullable=True)
    broker_response = Column(JSON, nullable=True)

    # Did this fill OPEN, ADD_TO, REDUCE, or CLOSE the position?
    fill_type       = Column(String(8), default="OPEN")
    realized_pnl    = Column(Float, default=0.0)        # only non-zero for REDUCE/CLOSE

    is_paper        = Column(Boolean, default=True, index=True)

    __table_args__ = (
        Index("ix_exec_fills_order_time", "order_id", "filled_at"),
        Index("ix_exec_fills_user_time",  "user_id", "filled_at"),
    )
